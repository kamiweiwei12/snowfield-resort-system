-- V1__baseline.sql
-- 雪野营地数据库基线迁移（对应 docs/DATABASE_CONTRACT.md §1 全局规则）。
--
-- 范围说明：S2 只建立「身份与权限」最小闭环（app_user / role / user_role），
-- 用于验证 Flyway 空库迁移、数据库约束与 MyBatis 映射链路真实可用。
-- 营地/资源/价格/订单等其余表在 S3 按契约分批迁移，不在本文件预置。

-- 角色：一期只有 CUSTOMER/ADMIN，但保留规范化角色表以支持权限演示（契约 §2 身份与权限）。
CREATE TABLE role (
    role_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(32)  NOT NULL,
    name       varchar(64)  NOT NULL,
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_role_code UNIQUE (code),
    CONSTRAINT ck_role_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]*$')
);

-- 用户：软停用优先于删除；存在交易历史后不得物理删除（契约 §1）。
CREATE TABLE app_user (
    user_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    display_name  varchar(64)  NOT NULL,
    phone         varchar(32),
    status        varchar(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    -- 邮箱一律小写存储，避免大小写不同的同一邮箱注册出两个账号。
    CONSTRAINT ck_app_user_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- 用户角色关联：复合主键天然阻止同一用户重复授予同一角色（契约 §2）。
CREATE TABLE user_role (
    user_id    bigint      NOT NULL,
    role_id    bigint      NOT NULL,
    granted_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES role (role_id) ON DELETE RESTRICT
);

-- 外键反向查询列按工作负载建索引（AGENTS.md §4）。
CREATE INDEX ix_user_role_role_id ON user_role (role_id);

-- 种子角色：管理端与顾客端的权限入口依赖它们存在。
INSERT INTO role (code, name) VALUES
    ('CUSTOMER', '顾客'),
    ('ADMIN', '管理员');
