-- V5__lodging_reservation.sql
-- BK-03 配套：住宿/日营占用表与住宿时间排斥约束。
-- 对应 docs/DATABASE_CONTRACT.md §2「住宿/日营占用」。
--
-- 本迁移是住宿并发正确性的核心：
--   EXCLUDE USING gist (resource_unit_id WITH =, stay_period WITH &&)
--   WHERE (occupancy_status IN ('HELD','CONFIRMED','IN_USE'))
-- 由数据库保证同一资源在重叠时段内至多一条有效占用，应用层的「先查后写」只是优化，
-- 不是正确性来源（AGENTS.md §2、ADR-003）。

-- 外层需要在预订并发出现时串行化同一资源的占用写入，
-- 排斥约束本身已能阻止重叠插入，无需额外加锁表。

CREATE TABLE lodging_reservation (
    reservation_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id    bigint      NOT NULL,
    resource_unit_id bigint      NOT NULL,
    stay_mode        varchar(16) NOT NULL,
    stay_period      tstzrange   NOT NULL,
    guest_count      integer     NOT NULL,
    occupancy_status varchar(16) NOT NULL DEFAULT 'HELD',
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    -- 契约：order_item_id UQ/FK —— 一个订单项至多对应一条住宿占用
    CONSTRAINT uq_lodging_reservation_order_item UNIQUE (order_item_id),
    CONSTRAINT fk_lodging_reservation_item FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id) ON DELETE CASCADE,
    CONSTRAINT fk_lodging_reservation_unit FOREIGN KEY (resource_unit_id) REFERENCES resource_unit (resource_unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_lodging_reservation_stay_mode CHECK (stay_mode IN ('OVERNIGHT', 'DAY_PASS')),
    -- OccupancyStatus 独立于 OrderItemStatus：只表达是否仍占用时间区间（契约 §2 明确）
    CONSTRAINT ck_lodging_reservation_occupancy CHECK (occupancy_status IN ('HELD', 'CONFIRMED', 'IN_USE', 'RELEASED')),
    CONSTRAINT ck_lodging_reservation_guest_count CHECK (guest_count > 0),
    -- 半开区间 [start,end) 必须非空（AGENTS.md §3）
    CONSTRAINT ck_lodging_reservation_period_nonempty CHECK (NOT isempty(stay_period)),
    -- 必须是真正的区间而非单个时刻：空区间已由上一约束拒绝，此处再保证上下界存在
    CONSTRAINT ck_lodging_reservation_period_bounded CHECK (lower(stay_period) IS NOT NULL AND upper(stay_period) IS NOT NULL)
);

CREATE INDEX ix_lodging_reservation_order_item ON lodging_reservation (order_item_id);
-- 资源维度按时间查询（可用性查询、排斥冲突排查）
CREATE INDEX ix_lodging_reservation_unit ON lodging_reservation USING gist (resource_unit_id, stay_period);

-- 契约核心：有效占用不得重叠。
-- RELEASED 必须排除在谓词外，否则已取消/过期的订单会永久阻塞同一资源。
ALTER TABLE lodging_reservation
    ADD CONSTRAINT ex_lodging_reservation_no_overlap
    EXCLUDE USING gist (
        resource_unit_id WITH =,
        stay_period WITH &&
    )
    WHERE (occupancy_status IN ('HELD', 'CONFIRMED', 'IN_USE'));

-- 占用状态与订单项状态的同步发生在同一个业务事务内（ADR-009），
-- 契约明确「不得由两个任意入口各自维护」，因此不在数据库用触发器强制双写；
-- 此处只提供一个历史记录表，便于审计状态变迁。
CREATE TABLE lodging_reservation_status_history (
    history_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id bigint      NOT NULL,
    from_status    varchar(16),
    to_status      varchar(16) NOT NULL,
    reason         varchar(255),
    changed_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_lodging_history_reservation FOREIGN KEY (reservation_id) REFERENCES lodging_reservation (reservation_id) ON DELETE CASCADE,
    CONSTRAINT ck_lodging_history_from CHECK (from_status IS NULL OR from_status IN ('HELD', 'CONFIRMED', 'IN_USE', 'RELEASED')),
    CONSTRAINT ck_lodging_history_to CHECK (to_status IN ('HELD', 'CONFIRMED', 'IN_USE', 'RELEASED'))
);

CREATE INDEX ix_lodging_history_reservation ON lodging_reservation_status_history (reservation_id, changed_at);
