-- DB-02：营地、季节与住宿资源（对应 docs/DATABASE_CONTRACT.md §2「营地、季节与住宿资源」）。
--
-- 前置：docs/DATABASE_CONTRACT.md v1.0-rc。本迁移只按现存契约落地，不新增契约语义。
-- 注意：契约冻结 PR 若是把某张表改成不同定义，本文件需随契约变更重做，不得直接编辑已进入 develop 的迁移。

-- 营地：系统唯一的时间/币种权威来源。
-- 先装 btree_gist：契约要求住宿排斥约束 EXCLUDE USING gist (resource_unit_id WITH =, stay_period WITH &&)
-- 需要它为 bigint 等标量类型提供 GiST 操作符类，本迁移的维修区间索引同样依赖它。
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE campground (
    campground_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(32)  NOT NULL,
    name          varchar(128) NOT NULL,
    timezone      varchar(64)  NOT NULL,
    currency      char(3)      NOT NULL,
    status        varchar(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_campground_code UNIQUE (code),
    -- 币种一期固定 CNY（AGENTS.md §3），时区固定业务时区（ADR-005）。
    CONSTRAINT ck_campground_currency CHECK (currency = 'CNY'),
    CONSTRAINT ck_campground_timezone CHECK (timezone = 'Asia/Shanghai'),
    CONSTRAINT ck_campground_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 季节：只是日期分类，不是全局模式开关（契约原文）。
CREATE TABLE season (
    season_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campground_id bigint      NOT NULL,
    code          varchar(32) NOT NULL,
    name          varchar(64) NOT NULL,
    start_date    date        NOT NULL,
    end_date      date        NOT NULL,
    CONSTRAINT fk_season_campground FOREIGN KEY (campground_id) REFERENCES campground (campground_id) ON DELETE RESTRICT,
    CONSTRAINT uq_season_campground_code UNIQUE (campground_id, code),
    -- 契约：CHECK end>=start
    CONSTRAINT ck_season_date_order CHECK (end_date >= start_date)
);

CREATE INDEX ix_season_campground_id ON season (campground_id);

-- 资源类型：base_price 是唯一基础价来源（契约 §价格）。
CREATE TABLE resource_type (
    resource_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campground_id    bigint        NOT NULL,
    code             varchar(32)   NOT NULL,
    name             varchar(128)  NOT NULL,
    kind             varchar(32)   NOT NULL,
    base_capacity    integer       NOT NULL,
    base_price       numeric(12,2) NOT NULL,
    status           varchar(16)   NOT NULL DEFAULT 'ACTIVE',
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_resource_type_campground FOREIGN KEY (campground_id) REFERENCES campground (campground_id) ON DELETE RESTRICT,
    CONSTRAINT uq_resource_type_campground_code UNIQUE (campground_id, code),
    CONSTRAINT ck_resource_type_kind CHECK (kind IN ('GRASS_SITE', 'PLATFORM_SITE', 'RV_SITE', 'HOMESTAY_ROOM', 'CABIN')),
    CONSTRAINT ck_resource_type_base_capacity CHECK (base_capacity > 0),
    CONSTRAINT ck_resource_type_base_price CHECK (base_price >= 0),
    CONSTRAINT ck_resource_type_status CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE', 'RETIRED'))
);

CREATE INDEX ix_resource_type_campground_id ON resource_type (campground_id);

-- 资源单元：单件资源，真实可用性结合开放规则与订单时间占用（契约原文）。
CREATE TABLE resource_unit (
    resource_unit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type_id bigint       NOT NULL,
    code             varchar(32)  NOT NULL,
    name             varchar(128) NOT NULL,
    capacity         integer      NOT NULL,
    status           varchar(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at       timestamptz  NOT NULL DEFAULT now(),
    updated_at       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_resource_unit_type FOREIGN KEY (resource_type_id) REFERENCES resource_type (resource_type_id) ON DELETE RESTRICT,
    CONSTRAINT uq_resource_unit_type_code UNIQUE (resource_type_id, code),
    CONSTRAINT ck_resource_unit_capacity CHECK (capacity > 0),
    CONSTRAINT ck_resource_unit_status CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE', 'RETIRED'))
);

CREATE INDEX ix_resource_unit_resource_type_id ON resource_unit (resource_type_id);

-- 资源类型支持哪些住宿模式。D-001 方案B 要求资源类型级规则在发布时校验此表。
CREATE TABLE resource_type_stay_mode (
    resource_type_id bigint     NOT NULL,
    stay_mode        varchar(16) NOT NULL,
    CONSTRAINT pk_resource_type_stay_mode PRIMARY KEY (resource_type_id, stay_mode),
    CONSTRAINT fk_resource_type_stay_mode_type FOREIGN KEY (resource_type_id) REFERENCES resource_type (resource_type_id) ON DELETE CASCADE,
    CONSTRAINT ck_resource_type_stay_mode CHECK (stay_mode IN ('OVERNIGHT', 'DAY_PASS'))
);

-- 开放规则：墙上时钟语义（ADR-011），故用 time 而非 timestamptz。
CREATE TABLE resource_open_rule (
    open_rule_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_unit_id bigint      NOT NULL,
    valid_from       date        NOT NULL,
    valid_to         date        NOT NULL,
    weekday          smallint    NOT NULL,
    open_time        time        NOT NULL,
    close_time       time        NOT NULL,
    is_open          boolean     NOT NULL DEFAULT true,
    priority         integer     NOT NULL DEFAULT 0,
    CONSTRAINT fk_open_rule_unit FOREIGN KEY (resource_unit_id) REFERENCES resource_unit (resource_unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_open_rule_date_order CHECK (valid_to >= valid_from),
    -- ISO-8601 星期：1=周一 .. 7=周日（契约 CHECK 1..7）
    CONSTRAINT ck_open_rule_weekday CHECK (weekday BETWEEN 1 AND 7),
    -- 半开区间 [open_time, close_time)（AGENTS.md §3）
    CONSTRAINT ck_open_rule_time_order CHECK (close_time > open_time)
);

CREATE INDEX ix_open_rule_unit_id ON resource_open_rule (resource_unit_id);
CREATE INDEX ix_open_rule_unit_validity ON resource_open_rule (resource_unit_id, valid_from, valid_to);

-- 维修区间：tstzrange 需 btree_gist 才能参与排斥/索引比较，此处只用 GiST 索引。
CREATE TABLE resource_maintenance (
    maintenance_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_unit_id bigint      NOT NULL,
    period           tstzrange   NOT NULL,
    status           varchar(16) NOT NULL DEFAULT 'OPEN',
    reason           text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_maintenance_unit FOREIGN KEY (resource_unit_id) REFERENCES resource_unit (resource_unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_maintenance_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    -- 区间必须非空，否则 len() 与包含判断都无意义（AGENTS.md §3 半开区间语义）
    CONSTRAINT ck_maintenance_period_nonempty CHECK (NOT isempty(period))
);

-- 可用性查询要判断「某时刻是否落在维修区间内」，GiST 索引服务 tstzrange 的 && 运算。
CREATE INDEX ix_maintenance_unit_period ON resource_maintenance USING gist (resource_unit_id, period);
