-- V3__price_rules_and_calendar.sql
-- DB-03：节假日、价格规则与价格日历（对应 docs/DATABASE_CONTRACT.md §2「价格」）。
--
-- 本迁移严格按 v1.0-rc 落地，不引入 PR #2 中尚未合并的 D-005 之外的任何语义：
-- 关于 price_rule 的 resource_type_id 与 stay_mode 同时为空的语义，
-- v1.0-rc 未作规定（ISSUES R5-04 仍 OPEN_FOR_REVIEW），本迁移刻意不加「至少一项非空」CHECK，
-- 以免在契约裁定前就把某一方语义写死进已发布迁移。

CREATE TABLE holiday (
    holiday_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campground_id bigint       NOT NULL,
    holiday_date  date         NOT NULL,
    name          varchar(128) NOT NULL,
    CONSTRAINT fk_holiday_campground FOREIGN KEY (campground_id) REFERENCES campground (campground_id) ON DELETE RESTRICT,
    CONSTRAINT uq_holiday_campground_date UNIQUE (campground_id, holiday_date)
);

CREATE INDEX ix_holiday_campground_id ON holiday (campground_id);

-- 价格规则：规则库 + 唯一最高优先级胜出（ADR-004）。
CREATE TABLE price_rule (
    price_rule_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campground_id    bigint        NOT NULL,
    -- D-001 方案B：允许为 NULL，表示全营地范围规则。
    resource_type_id bigint        NULL,
    -- 始终受 StayMode 枚举约束（契约原文）。
    stay_mode        varchar(16)   NULL,
    rule_type        varchar(32)   NOT NULL,
    operation        varchar(16)   NOT NULL,
    value            numeric(12,2) NOT NULL,
    priority         integer       NOT NULL,
    valid_from       date          NOT NULL,
    valid_to         date          NOT NULL,
    enabled          boolean       NOT NULL DEFAULT true,
    description      varchar(255),
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_price_rule_campground FOREIGN KEY (campground_id) REFERENCES campground (campground_id) ON DELETE RESTRICT,
    CONSTRAINT fk_price_rule_resource_type FOREIGN KEY (resource_type_id) REFERENCES resource_type (resource_type_id) ON DELETE RESTRICT,
    CONSTRAINT ck_price_rule_type CHECK (rule_type IN ('WEEKEND', 'SEASON', 'HOLIDAY', 'SPECIAL_DATE', 'MANUAL_OVERRIDE')),
    CONSTRAINT ck_price_rule_operation CHECK (operation IN ('FIXED', 'MULTIPLIER', 'ADDITION')),
    CONSTRAINT ck_price_rule_stay_mode CHECK (stay_mode IS NULL OR stay_mode IN ('OVERNIGHT', 'DAY_PASS')),
    CONSTRAINT ck_price_rule_validity CHECK (valid_to >= valid_from),
    -- FIXED/ADDITION 是真金金额，MULTIPLIER 是倍率；两者都必须非负。
    CONSTRAINT ck_price_rule_value CHECK (value >= 0)
);

CREATE INDEX ix_price_rule_campground_id ON price_rule (campground_id);
CREATE INDEX ix_price_rule_resource_type_id ON price_rule (resource_type_id);
-- 报价匹配按 (营地, 有效期) 过滤后取最高优先级，此索引服务该访问路径。
CREATE INDEX ix_price_rule_matching ON price_rule (campground_id, valid_from, valid_to, priority DESC)
    WHERE enabled;

-- 周末规则：ISO-8601 星期 1..7（契约 CHECK 1..7）
CREATE TABLE price_rule_weekday (
    price_rule_id bigint   NOT NULL,
    weekday       smallint NOT NULL,
    CONSTRAINT pk_price_rule_weekday PRIMARY KEY (price_rule_id, weekday),
    CONSTRAINT fk_price_rule_weekday_rule FOREIGN KEY (price_rule_id) REFERENCES price_rule (price_rule_id) ON DELETE CASCADE,
    CONSTRAINT ck_price_rule_weekday CHECK (weekday BETWEEN 1 AND 7)
);

-- 特定日期规则
CREATE TABLE price_rule_date (
    price_rule_id bigint NOT NULL,
    service_date  date   NOT NULL,
    CONSTRAINT pk_price_rule_date PRIMARY KEY (price_rule_id, service_date),
    CONSTRAINT fk_price_rule_date_rule FOREIGN KEY (price_rule_id) REFERENCES price_rule (price_rule_id) ON DELETE CASCADE
);

CREATE INDEX ix_price_rule_date_service_date ON price_rule_date (service_date);
