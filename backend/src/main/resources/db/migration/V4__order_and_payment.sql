-- V4__order_and_payment.sql
-- DB-04（第一阶段）：套餐目录、统一订单、订单明细、状态历史、模拟支付与价格快照。
-- 对应 docs/DATABASE_CONTRACT.md §2「套餐目录」「统一订单、支付与历史」。
--
-- 本迁移刻意不含以下两处，避免在契约冻结（PR #2）前把可能变动的结构写死：
--   1. package_component —— 它外键指向 ski_product / lift / equipment_model，
--      这三张表属于 B 侧模块（SKI-01/LIFT-01/EQ-01）尚未建立。等其落地后再建。
--   2. lodging_reservation —— 住宿时间排斥约束是并发正确性的核心，
--      需要在同一轮里与并发测试一起验证（BK-03），单独建表会给出未经验证的假象。

-- ---- 套餐目录（不含 package_component） ----

CREATE TABLE package_offer (
    package_offer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campground_id    bigint        NOT NULL,
    code             varchar(32)   NOT NULL,
    name             varchar(128)  NOT NULL,
    pricing_mode     varchar(32)   NOT NULL,
    pricing_value    numeric(12,2) NOT NULL,
    valid_from       date          NOT NULL,
    valid_to         date          NOT NULL,
    enabled          boolean       NOT NULL DEFAULT true,
    description      varchar(255),
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_package_offer_campground FOREIGN KEY (campground_id) REFERENCES campground (campground_id) ON DELETE RESTRICT,
    -- v1.0-rc：单营地部署下 code 作为外部稳定标识，全局唯一（契约 §2 明确边界）。
    CONSTRAINT uq_package_offer_code UNIQUE (code),
    CONSTRAINT ck_package_offer_pricing_mode CHECK (pricing_mode IN ('FIXED_TOTAL', 'DISCOUNT_AMOUNT', 'DISCOUNT_RATE')),
    CONSTRAINT ck_package_offer_validity CHECK (valid_to >= valid_from),
    CONSTRAINT ck_package_offer_pricing_value CHECK (pricing_value >= 0),
    -- DISCOUNT_RATE 取 0..1 之间的小数（契约原文）。
    CONSTRAINT ck_package_offer_rate_range CHECK (pricing_mode <> 'DISCOUNT_RATE' OR pricing_value <= 1)
);

CREATE INDEX ix_package_offer_campground_id ON package_offer (campground_id);

-- ---- 统一订单 ----

CREATE TABLE customer_order (
    order_id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no                    varchar(32)   NOT NULL,
    user_id                     bigint        NOT NULL,
    campground_id               bigint        NOT NULL,
    status                      varchar(24)   NOT NULL DEFAULT 'PENDING_PAYMENT',
    currency                    char(3)       NOT NULL DEFAULT 'CNY',
    total_amount                numeric(12,2) NOT NULL DEFAULT 0,
    create_idempotency_key      varchar(128)  NOT NULL,
    create_request_fingerprint  varchar(128)  NOT NULL,
    expires_at                  timestamptz   NOT NULL,
    version                     integer       NOT NULL DEFAULT 0,
    created_at                  timestamptz   NOT NULL DEFAULT now(),
    updated_at                  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_campground FOREIGN KEY (campground_id) REFERENCES campground (campground_id) ON DELETE RESTRICT,
    CONSTRAINT uq_order_no UNIQUE (order_no),
    -- 创建幂等键作用域为 (user_id, key)（契约原文）。
    CONSTRAINT uq_order_user_idempotency UNIQUE (user_id, create_idempotency_key),
    CONSTRAINT ck_order_status CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'IN_USE', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_order_currency CHECK (currency = 'CNY'),
    -- 订单总额不得为负（契约：总额减优惠后不得为负）。
    CONSTRAINT ck_order_total_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_order_version CHECK (version >= 0)
);

CREATE INDEX ix_order_user_id ON customer_order (user_id);
CREATE INDEX ix_order_campground_id ON customer_order (campground_id);
-- 待支付订单过期扫描按 (status, expires_at) 访问。
CREATE INDEX ix_order_pending_expiry ON customer_order (expires_at) WHERE status = 'PENDING_PAYMENT';

-- ---- 成交套餐快照 ----

CREATE TABLE order_package (
    order_package_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                 bigint        NOT NULL,
    package_offer_id         bigint        NOT NULL,
    package_code_snapshot    varchar(32)   NOT NULL,
    package_name_snapshot    varchar(128)  NOT NULL,
    pricing_mode_snapshot    varchar(32)   NOT NULL,
    pricing_value_snapshot   numeric(12,2) NOT NULL,
    discount_amount          numeric(12,2) NOT NULL DEFAULT 0,
    subtotal_before_discount numeric(12,2) NOT NULL,
    CONSTRAINT fk_order_package_order FOREIGN KEY (order_id) REFERENCES customer_order (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_package_offer FOREIGN KEY (package_offer_id) REFERENCES package_offer (package_offer_id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_package_pricing_mode CHECK (pricing_mode_snapshot IN ('FIXED_TOTAL', 'DISCOUNT_AMOUNT', 'DISCOUNT_RATE')),
    CONSTRAINT ck_order_package_discount CHECK (discount_amount >= 0),
    CONSTRAINT ck_order_package_subtotal CHECK (subtotal_before_discount >= 0),
    -- 优惠不得超过小计（契约：DISCOUNT_AMOUNT 不得超过小计）。
    CONSTRAINT ck_order_package_discount_within_subtotal CHECK (discount_amount <= subtotal_before_discount)
);

CREATE INDEX ix_order_package_order_id ON order_package (order_id);
CREATE INDEX ix_order_package_offer_id ON order_package (package_offer_id);

-- ---- 订单明细 ----

CREATE TABLE order_item (
    order_item_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           bigint        NOT NULL,
    item_type          varchar(24)   NOT NULL,
    item_name_snapshot varchar(128)  NOT NULL,
    status             varchar(24)   NOT NULL DEFAULT 'HELD',
    order_package_id   bigint,
    quantity           integer       NOT NULL,
    unit_price         numeric(12,2) NOT NULL,
    subtotal           numeric(12,2) NOT NULL,
    price_explanation  jsonb,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES customer_order (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_item_package FOREIGN KEY (order_package_id) REFERENCES order_package (order_package_id) ON DELETE CASCADE,
    CONSTRAINT ck_order_item_type CHECK (item_type IN ('LODGING', 'SKI_TICKET', 'SKI_LESSON', 'LIFT_SLOT', 'EQUIPMENT_RENTAL')),
    CONSTRAINT ck_order_item_status CHECK (status IN ('HELD', 'CONFIRMED', 'IN_USE', 'FULFILLED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_item_subtotal CHECK (subtotal >= 0)
);

CREATE INDEX ix_order_item_order_id ON order_item (order_id);
CREATE INDEX ix_order_item_package_id ON order_item (order_package_id);

-- ---- 状态历史 ----

CREATE TABLE order_status_history (
    history_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint      NOT NULL,
    from_status varchar(24),
    to_status   varchar(24) NOT NULL,
    changed_by  bigint,
    reason      varchar(255),
    changed_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_order_history_order FOREIGN KEY (order_id) REFERENCES customer_order (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_history_user FOREIGN KEY (changed_by) REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_history_from CHECK (from_status IS NULL OR from_status IN ('PENDING_PAYMENT', 'CONFIRMED', 'IN_USE', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_order_history_to CHECK (to_status IN ('PENDING_PAYMENT', 'CONFIRMED', 'IN_USE', 'COMPLETED', 'CANCELLED', 'EXPIRED'))
);

CREATE INDEX ix_order_history_order_id ON order_status_history (order_id, changed_at);

CREATE TABLE order_item_status_history (
    history_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id   bigint      NOT NULL,
    from_status     varchar(24),
    to_status       varchar(24) NOT NULL,
    changed_by      bigint,
    reason          varchar(255),
    changed_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_history_item FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id) ON DELETE CASCADE,
    CONSTRAINT fk_item_history_user FOREIGN KEY (changed_by) REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_item_history_from CHECK (from_status IS NULL OR from_status IN ('HELD', 'CONFIRMED', 'IN_USE', 'FULFILLED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_item_history_to CHECK (to_status IN ('HELD', 'CONFIRMED', 'IN_USE', 'FULFILLED', 'CANCELLED', 'EXPIRED'))
);

CREATE INDEX ix_item_history_item_id ON order_item_status_history (order_item_id, changed_at);

-- ---- 模拟支付 ----

CREATE TABLE payment (
    payment_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            bigint        NOT NULL,
    payment_no          varchar(32)   NOT NULL,
    status              varchar(16)   NOT NULL,
    amount              numeric(12,2) NOT NULL,
    -- 禁止真实收款：method 恒为 SIMULATED（AGENTS.md §10）。
    method              varchar(16)   NOT NULL DEFAULT 'SIMULATED',
    idempotency_key     varchar(128)  NOT NULL,
    request_fingerprint varchar(128)  NOT NULL,
    paid_at             timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES customer_order (order_id) ON DELETE CASCADE,
    CONSTRAINT uq_payment_no UNIQUE (payment_no),
    -- 支付幂等键作用域为 (order_id, key)（契约原文）。
    CONSTRAINT uq_payment_order_idempotency UNIQUE (order_id, idempotency_key),
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    CONSTRAINT ck_payment_method CHECK (method = 'SIMULATED'),
    CONSTRAINT ck_payment_amount CHECK (amount >= 0),
    -- 成功支付必须有支付时刻；成功金额等于订单总额由应用层在同事务内保证（契约要求）。
    CONSTRAINT ck_payment_succeeded_has_paid_at CHECK (status <> 'SUCCEEDED' OR paid_at IS NOT NULL)
);

CREATE INDEX ix_payment_order_id ON payment (order_id);

-- 一张订单至多一条 SUCCEEDED 支付（契约原文，数据库兜底并发双成功）。
CREATE UNIQUE INDEX uq_payment_succeeded_per_order
    ON payment (order_id)
    WHERE status = 'SUCCEEDED';

-- ---- 价格快照 ----

CREATE TABLE price_snapshot_line (
    snapshot_line_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id       bigint        NOT NULL,
    service_date        date          NOT NULL,
    rule_id             bigint,
    rule_name_snapshot  varchar(128),
    operation_snapshot  varchar(16),
    rule_value_snapshot numeric(12,2),
    amount              numeric(12,2) NOT NULL,
    CONSTRAINT fk_snapshot_line_item FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id) ON DELETE CASCADE,
    -- 规则被删除后快照仍须可追溯，故只允许 RESTRICT。
    CONSTRAINT fk_snapshot_line_rule FOREIGN KEY (rule_id) REFERENCES price_rule (price_rule_id) ON DELETE RESTRICT,
    CONSTRAINT ck_snapshot_line_operation CHECK (operation_snapshot IS NULL OR operation_snapshot IN ('FIXED', 'MULTIPLIER', 'ADDITION')),
    CONSTRAINT ck_snapshot_line_amount CHECK (amount >= 0)
);

CREATE INDEX ix_snapshot_line_item_id ON price_snapshot_line (order_item_id, service_date);
